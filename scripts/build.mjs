import {cp,mkdir,readFile,writeFile,rm,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
const dest='dist';
await rm(dest,{recursive:true,force:true});
await mkdir(dest+'/vendor',{recursive:true});
for(const file of ['index.html','styles.css','icon.svg','manifest.webmanifest','.nojekyll'])await cp(file,dest+'/'+file);
await cp('src',dest+'/src',{recursive:true});
const copy=async(source,target)=>cp('node_modules/'+source,dest+'/vendor/'+target);
await copy('codemirror/lib/codemirror.js','codemirror.js');
await copy('codemirror/lib/codemirror.css','codemirror.css');
for(const theme of ['dracula','eclipse'])await copy('codemirror/theme/'+theme+'.css',theme+'.css');
for(const name of ['xml','javascript','css','htmlmixed','python','markdown'])await copy('codemirror/mode/'+name+'/'+name+'.js',name+'.js');
for(const addon of ['edit/closebrackets','edit/closetag','edit/matchbrackets','search/searchcursor','comment/comment','hint/show-hint','hint/anyword-hint','hint/javascript-hint','hint/xml-hint','hint/html-hint','hint/css-hint'])await copy('codemirror/addon/'+addon+'.js',addon.split('/').pop()+'.js');
await copy('codemirror/addon/hint/show-hint.css','show-hint.css');
await copy('jszip/dist/jszip.min.js','jszip.js');
await copy('es-module-lexer/dist/lexer.js','lexer.js');
await copy('prettier/standalone.js','prettier.js');
for(const plugin of ['babel','estree','html','postcss','markdown'])await copy('prettier/plugins/'+plugin+'.js','prettier-'+plugin+'.js');
await mkdir(dest+'/licenses',{recursive:true});
for(const[pkg,file]of [['codemirror','LICENSE'],['jszip','LICENSE.markdown'],['es-module-lexer','LICENSE'],['prettier','LICENSE']])await cp('node_modules/'+pkg+'/'+file,dest+'/licenses/'+pkg+'.txt');
const paths=[];
async function walk(dir){for(const entry of await readdir(dir,{withFileTypes:true})){const p=path.join(dir,entry.name);if(entry.isDirectory())await walk(p);else paths.push('./'+path.relative(dest,p).replaceAll('\\','/'));}}
await walk(dest);
const hash=createHash('sha256');
for(const p of [...paths].sort())hash.update(await readFile(path.join(dest,p.slice(2))));
const version=hash.digest('hex').slice(0,12);
let sw=await readFile('sw.js','utf8');
sw=sw.replace("kgcode-shell-v2.0.0",'kgcode-shell-'+version).replace(/const SHELL=\[[\s\S]*?\];/,'const SHELL='+JSON.stringify(['./',...paths])+';');
await writeFile(dest+'/sw.js',sw);
console.log('Build pronto: '+paths.length+' arquivos. Versão '+version);
